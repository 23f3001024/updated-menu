-- Run this once in the Supabase SQL Editor (Dashboard → SQL → New query).
-- Creates the table the menu API reads and writes.

create table if not exists public.menu_items (
  id         uuid primary key default gen_random_uuid(),
  position   bigint generated by default as identity,
  cat        text    not null,
  diet       text    not null default 'v',
  name       text    not null,
  price      text    not null,          -- number OR "299 / 349 / 399"
  descr      text    not null default '',
  chef       boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists menu_items_position_idx on public.menu_items (position);

-- The API talks to Supabase with the service-role key (server-side only), which
-- bypasses Row Level Security. RLS is enabled with no public policies so the
-- table cannot be read or written with the anon/public key.
alter table public.menu_items enable row level security;

-- Menu categories (sections). Managed from the dashboard; seeded from
-- api/_lib/seed.js on first read if empty.
create table if not exists public.categories (
  key        text primary key,
  label      text    not null,
  ico        text    not null default '',
  position   bigint  generated by default as identity,
  created_at timestamptz not null default now()
);

create index if not exists categories_position_idx on public.categories (position);

alter table public.categories enable row level security;
